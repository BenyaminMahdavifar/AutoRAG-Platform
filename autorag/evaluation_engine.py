"""
Evaluation Engine Subsystem for AutoRAG Platform.
Calculates Retrieval Metrics, Answer Quality Metrics, and overall Composite RAG Score.
Supports both deterministic math algorithms and LLM-assisted metrics.
"""

import math
import re
from typing import List, Dict, Any, Tuple, Optional

from .types import (
    Dataset, DatasetItem, Chunk, RetrievalMetrics, AnswerMetrics, EvaluationResult, PipelineConfig
)
from .retrieval_engine import cosine_similarity, BM25Scorer
from .connections import LocalTFIDFEmbedder, OpenAICompatibleClient


class EvaluationEngine:
    """Evaluates RAG pipeline retrieval performance and answer quality."""

    def __init__(self, llm_client: Optional[OpenAICompatibleClient] = None):
        self.llm_client = llm_client
        self.text_embedder = LocalTFIDFEmbedder(dimension=256)

    def _calculate_string_similarity(self, s1: str, s2: str) -> float:
        """Calculate cosine similarity of TF-IDF vectors between two strings."""
        if not s1.strip() or not s2.strip():
            return 0.0
        vecs = self.text_embedder.fit_transform([s1, s2])
        return cosine_similarity(vecs[0], vecs[1])

    def evaluate_retrieval(
        self, retrieved_chunks: List[Tuple[Chunk, float]], target_chunk_id: Optional[str], ground_truth: str
    ) -> RetrievalMetrics:
        """Calculate deterministic retrieval precision, recall, hit rate, MRR, NDCG."""
        if not retrieved_chunks:
            return RetrievalMetrics()

        retrieved_ids = [c.chunk_id for c, _ in retrieved_chunks]

        # 1. Hit Rate & Rank
        hit = 1.0 if target_chunk_id in retrieved_ids else 0.0
        mrr = 0.0
        if target_chunk_id in retrieved_ids:
            rank = retrieved_ids.index(target_chunk_id) + 1
            mrr = 1.0 / rank

        # 2. Context Recall & Precision based on ground truth text overlap
        relevant_flags = []
        for chunk, score in retrieved_chunks:
            sim = self._calculate_string_similarity(chunk.text, ground_truth)
            relevant_flags.append(1.0 if sim > 0.25 or chunk.chunk_id == target_chunk_id else 0.0)

        precision = sum(relevant_flags) / max(1, len(relevant_flags))
        recall = 1.0 if sum(relevant_flags) > 0 or hit > 0 else 0.0

        # 3. NDCG Calculation
        dcg = sum(rel / math.log2(idx + 2) for idx, rel in enumerate(relevant_flags))
        idcg = sum(1.0 / math.log2(idx + 2) for idx in range(int(sum(relevant_flags)) or 1))
        ndcg = dcg / idcg if idcg > 0 else 0.0

        return RetrievalMetrics(
            precision=round(precision, 4),
            recall=round(recall, 4),
            hit_rate=round(hit, 4),
            mrr=round(mrr, 4),
            ndcg=round(ndcg, 4)
        )

    def evaluate_answer(
        self, question: str, answer: str, context_str: str, ground_truth: str
    ) -> AnswerMetrics:
        """Calculate answer quality metrics: Accuracy/Answer Correctness, Completeness, Relevance via LLM-as-a-judge."""
        if not answer.strip():
            return AnswerMetrics()

        metrics = AnswerMetrics()

        if self.llm_client:
            prompt = f"""
You are an impartial judge evaluating an answer generated by an AI assistant.
Question: {question}
Reference Answer (Ground Truth): {ground_truth}
Assistant Answer: {answer}

Evaluate the assistant's answer on three criteria, providing a score from 0.0 to 1.0 for each:
1. Accuracy: Does the answer contain correct information compared to the reference? (0.0 to 1.0)
2. Completeness: Does the answer fully address the question? (0.0 to 1.0)
3. Relevance: Is the answer focused on the question without unnecessary tangents? (0.0 to 1.0)

Provide ONLY a JSON object with keys "accuracy", "completeness", "relevance", and float values.
"""
            try:
                res = self.llm_client.chat_completion(
                    messages=[{"role": "user", "content": prompt}],
                    system_prompt="You are a JSON metric evaluator. Output ONLY valid JSON.",
                    temperature=0.0
                )
                import json
                parsed = json.loads(res.get("text", "{}"))
                metrics.accuracy = float(parsed.get("accuracy", 0.0))
                metrics.completeness = float(parsed.get("completeness", 0.0))
                metrics.relevance = float(parsed.get("relevance", 0.0))
                metrics.answer_correctness = metrics.accuracy
                metrics.faithfulness = metrics.accuracy  # Backward compatibility alias
            except Exception as e:
                raise RuntimeError(f"LLM Evaluation Failed: {str(e)}") from e
        else:
            raise RuntimeError("LLM Client is required for answer evaluation.")

        return metrics

    def aggregate_retrieval_metrics(self, r_list: List[RetrievalMetrics]) -> RetrievalMetrics:
        if not r_list:
            return RetrievalMetrics()
        n = len(r_list)
        return RetrievalMetrics(
            precision=round(sum(r.precision for r in r_list) / n, 4),
            recall=round(sum(r.recall for r in r_list) / n, 4),
            hit_rate=round(sum(r.hit_rate for r in r_list) / n, 4),
            mrr=round(sum(r.mrr for r in r_list) / n, 4),
            ndcg=round(sum(r.ndcg for r in r_list) / n, 4)
        )

    def aggregate_answer_metrics(self, a_list: List[AnswerMetrics]) -> AnswerMetrics:
        if not a_list:
            return AnswerMetrics()
        n = len(a_list)
        avg_acc = round(sum(getattr(a, "answer_correctness", getattr(a, "accuracy", getattr(a, "faithfulness", 0.0))) for a in a_list) / n, 4)
        return AnswerMetrics(
            accuracy=avg_acc,
            answer_correctness=avg_acc,
            completeness=round(sum(a.completeness for a in a_list) / n, 4),
            relevance=round(sum(a.relevance for a in a_list) / n, 4),
            faithfulness=avg_acc
        )

    def calculate_composite_score(
        self, r_metrics: RetrievalMetrics, a_metrics: AnswerMetrics
    ) -> float:
        """Calculate overall composite score (0.0 to 1.0).
        Formula: 0.7 * Hit Rate + 0.3 * Answer Correctness
        (Note: answer_correctness was previously labeled faithfulness; numerical value is identical).
        """
        ans_corr = getattr(a_metrics, "answer_correctness", 0.0)
        if not ans_corr:
            ans_corr = getattr(a_metrics, "faithfulness", 0.0) or getattr(a_metrics, "accuracy", 0.0)
        eval_score_component = ans_corr
        composite = 0.7 * r_metrics.hit_rate + 0.3 * eval_score_component
        return round(composite, 4)
